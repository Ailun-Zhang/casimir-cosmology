# sm-blind R16 V1: (1) convert mr's math/rge.m (3-loop SM beta functions of Bednyakov-Pikelner-Velizhanin,
# arXiv:1210.6873, 1212.6829, 1303.4364) into a generated Python module; (2) parse the published 3-loop
# RGE appendix of Buttazzo et al. (arXiv:1307.3536v2 LaTeX, appendix "SM RGE equations up to three loops")
# and compare TERM BY TERM (monomial coefficients) loop order by loop order.
import os, sys, re, json
import sympy as sp
from sympy.parsing.sympy_parser import parse_expr, standard_transformations, implicit_multiplication, convert_xor
sys.stdout.reconfigure(encoding='utf-8')
MY = r'D:\0PhD\Perimeter\Research\2026\Directional_Null_Energy_Cosmology\07_reviews\R16_v12_round3\sm_mapping_blind'
RGEM = os.path.join(MY, 'inputs', '20261014_mr_extracted', 'mr-master', 'math', 'rge.m')
TEX = os.path.join(MY, 'inputs', '20261014_arxiv_src_extracted', 'Buttazzo2013_1307.3536', 'artv2.tex')
OUT = os.path.join(MY, 'work', 'rge_bpv3_gen.py')
RES = os.path.join(MY, 'results', 'rge_termcheck_vs_Buttazzo.json')

# ---------------- (1) rge.m -> sympy ----------------
txt = open(RGEM, encoding='utf-8', errors='replace').read()
txt = re.sub(r'\(\*.*?\*\)', ' ', txt, flags=re.S)
A = sp.symbols('a1 a2 as_ at ab atau alam')
a1, a2, as_, at, ab, atau, alam = A
h, NG, CF, CA, TF, NC, z3, z4, z5 = sp.symbols('h NG CF CA TF NC zeta3 zeta4 zeta5')
loc = dict(a1=a1, a2=a2, as_=as_, at=at, ab=ab, atau=atau, alam=alam, h=h, NG=NG, CF=CF, CA=CA, TF=TF, NC=NC,
           zeta3=z3, zeta4=z4, zeta5=z5)
subsSM = {NG: 3, CF: sp.Rational(4, 3), CA: 3, TF: sp.Rational(1, 2), NC: 3}
names = ['a1', 'a2', 'as', 'at', 'ab', 'atau', 'alam']
betas = {}
for nm in names:
    m = re.search(r'beta\[' + nm + r'\]\s*=\s*\(', txt)
    i = m.end() - 1; depth = 0
    for j in range(i, len(txt)):
        if txt[j] == '(':
            depth += 1
        elif txt[j] == ')':
            depth -= 1
            if depth == 0:
                break
    body = txt[i:j + 1]
    body = body.replace('Zeta[3]', 'zeta3').replace('Zeta[4]', 'zeta4').replace('Zeta[5]', 'zeta5')
    body = re.sub(r'\bas\b', 'as_', body).replace('^', '**')
    assert '[' not in body, nm
    e = sp.expand(parse_expr(body, local_dict=loc).subs(subsSM).subs(h, 1))
    # loop order from total degree in the a's (L-loop term of beta[a] has degree L+1); h-convention differs
    P = sp.Poly(e, *A)
    parts = {1: 0, 2: 0, 3: 0}
    for mon, c in P.terms():
        parts[sum(mon) - 1] += c * sp.Mul(*[v ** p for v, p in zip(A, mon)])
    betas[nm] = {L: sp.expand(parts[L]) for L in (1, 2, 3)}
    rest = sp.expand(e - sum(betas[nm].values()))
    assert rest == 0, (nm, rest)

# generated python module (zeta values numeric)
zv = {z3: sp.zeta(3), z4: sp.zeta(4), z5: sp.zeta(5)}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('# GENERATED by rge_convert_check.py from mr-master/math/rge.m (BPV 3-loop SM betas).\n')
    f.write('# beta[x] = dx/dt, t = ln(mu^2); a1=(5/3)gY^2/(16pi^2), a2=g2^2/(16pi^2), as_=g3^2/(16pi^2),\n')
    f.write('# at=yt^2/(16pi^2), ab, atau likewise, alam=lambda/(16pi^2)  [V = lambda(|H|^2-v^2/2)^2].\n')
    f.write('def betas(L, a1, a2, as_, at, ab, atau, alam):\n')
    for L in (1, 2, 3):
        f.write('    if L == %d:\n' % L)
        outs = []
        for nm in names:
            ex = sp.N(betas[nm][L].subs(zv), 20)
            f.write('        b_%s = %s\n' % (nm, sp.pycode(ex).replace('math.', '')))
            outs.append('b_' + nm)
        f.write('        return (%s)\n' % ', '.join(outs))
    f.write('    raise ValueError(L)\n')
print('generated', OUT)

# ---------------- (2) Buttazzo appendix LaTeX -> sympy ----------------
tex = open(TEX, encoding='utf-8', errors='replace').read()
i0 = tex.index(r'\section{SM RGE equations up to three loops}')
i1 = tex.index(r'\section{Effective potential at two loops}')
app = '\n'.join(l for l in tex[i0:i1].splitlines() if not l.lstrip().startswith('%'))
blocks = re.findall(r'\\begin\{eqnarray\}(.*?)\\end\{eqnarray\}', app, flags=re.S)
K1, K2, K3, K4 = sp.symbols('K1 K2 K3 K4')
g1, g2, g3, yt, yb, ytau, lam, m2 = sp.symbols('g1 g2 g3 yt yb ytau lam m2')
locB = dict(K1=K1, K2=K2, K3=K3, K4=K4, g1=g1, g2=g2, g3=g3, yt=yt, yb=yb, ytau=ytau, lam=lam, m2=m2)


def frac_repl(s):
    # replace \frac{A}{B} -> ((A)/(B)) with nested braces
    while True:
        k = s.find(r'\frac')
        if k < 0:
            return s
        def grab(p):
            assert s[p] == '{', s[p:p + 30]
            d = 0
            for q in range(p, len(s)):
                if s[q] == '{':
                    d += 1
                elif s[q] == '}':
                    d -= 1
                    if d == 0:
                        return s[p + 1:q], q + 1
        p = k + 5
        while s[p] == ' ':
            p += 1
        num, p2 = grab(p)
        while s[p2] == ' ':
            p2 += 1
        den, p3 = grab(p2)
        s = s[:k] + '((' + num + ')/(' + den + '))' + s[p3:]


def tex2sym(rhs):
    s = rhs
    for a, b in [(r'(4\pi)^2', ' K1 '), (r'(4\pi)^4', ' K2 '), (r'(4\pi)^6', ' K3 '), (r'(4\pi)^8', ' K4 ')]:
        s = s.replace(a, b)
    s = re.sub(r'\\(nonumber|acapo|bigg|left|right|Big|big)', ' ', s)
    s = s.replace('\\\\', ' ').replace('&&', ' ').replace(r'\ .', ' ').replace(r'\,', ' ')
    s = re.sub(r'(?<=[ \d])\.(?=\s|$)', ' ', s)  # stray '.' from \right.
    s = frac_repl(s)
    s = re.sub(r'y_\s*\{?\\tau\s*\}?', 'ytau', s)
    s = re.sub(r'g_\s*([123])', r'g\1', s)
    s = re.sub(r'y_\s*([tb])', r'y\1', s)
    s = s.replace(r'\lambda', ' lam ')
    s = re.sub(r'\^\{(\d+)\}', r'^(\1)', s)
    s = s.replace('[', '(').replace(']', ')').replace('{', '(').replace('}', ')')
    s = re.sub(r'(\d)([A-Za-z])', r'\1 \2', s)
    s = re.sub(r'\s+', ' ', s)
    return parse_expr(s, local_dict=locB, transformations=standard_transformations + (implicit_multiplication, convert_xor))


lhs_map = [(r'dg_1^2', 'g1sq'), (r'dg_2^2', 'g2sq'), (r'dg_3^2', 'g3sq'), (r'd\lambda', 'lam'), (r'dm^2', 'm2'),
           (r'dy_t^2', 'ytsq'), (r'dy_b^2', 'ybsq'), (r'dy_\tau^2', 'ytausq')]
butt = {}
for blk in blocks:
    lhs, rhs = re.split(r'&=&', blk, maxsplit=1)
    key = None
    for pat, k in lhs_map:
        if pat in lhs.replace(' ', ''):
            key = k
    e = sp.expand(tex2sym(rhs))
    butt[key] = {L: sp.expand(e.coeff(Kk, -1)) for L, Kk in ((1, K1), (2, K2), (3, K3), (4, K4))}
    left = sp.expand(e - sum(butt[key][L] / Kk for L, Kk in ((1, K1), (2, K2), (3, K3), (4, K4))))
    assert left == 0, (key, left)
print('parsed Buttazzo blocks:', list(butt))

# ---------------- (3) term-by-term comparison ----------------
k16 = 16 * sp.pi ** 2
toG = {a1: g1 ** 2 / k16, a2: g2 ** 2 / k16, as_: g3 ** 2 / k16, at: yt ** 2 / k16, ab: yb ** 2 / k16,
       atau: ytau ** 2 / k16, alam: lam / k16}
pairs = [('g1sq', 'a1'), ('g2sq', 'a2'), ('g3sq', 'as'), ('lam', 'alam'), ('ytsq', 'at'), ('ybsq', 'ab'), ('ytausq', 'atau')]
report = {'source_rge': 'mr-master/math/rge.m (BPV 2012-13)', 'source_published': 'Buttazzo et al. JHEP 12 (2013) 089, arXiv:1307.3536v2, App. B (tex lines 2656-2966)',
          'convention': 'd(x)/d ln mu^2, g1 GUT-normalised, V=lambda(|H|^2-v^2/2)^2', 'checks': []}
nmono = 0; nbad = 0
for kb, kr in pairs:
    for L in (1, 2, 3):
        R = sp.expand((k16 * betas[kr][L].subs(toG) * k16 ** L).subs(zv))  # polynomial in g's
        Bt = butt[kb][L]
        if L == 3 or kb in ('ybsq', 'ytausq'):
            # Buttazzo: 3-loop only with y_t; y_b, y_tau RGEs only to 2 loops
            R = sp.expand(R.subs({yb: 0, ytau: 0})) if L == 3 else R
        if kb in ('ybsq', 'ytausq') and L == 3:
            continue
        PR = sp.Poly(R, g1, g2, g3, yt, yb, ytau, lam)
        PB = sp.Poly(Bt, g1, g2, g3, yt, yb, ytau, lam)
        monos = set(PR.as_dict()) | set(PB.as_dict())
        dR, dB = PR.as_dict(), PB.as_dict()
        for mo in sorted(monos):
            cr = float(dR.get(mo, 0)); cb = float(dB.get(mo, 0))
            exact_b = isinstance(dB.get(mo, 0), (sp.Integer, sp.Rational)) or dB.get(mo, 0) == 0
            tol = 1e-12 if exact_b else max(6e-4 * abs(cb), 1.2e-3)
            ok = abs(cr - cb) <= tol
            nmono += 1; nbad += (not ok)
            if not ok:
                report['checks'].append(dict(eq=kb, loop=L, monomial=str(sp.Mul(*[v ** p for v, p in zip((g1, g2, g3, yt, yb, ytau, lam), mo)])),
                                             coeff_rge_m=cr, coeff_Buttazzo=cb))
    # 4-loop pure QCD in g3 (Buttazzo has -2472.28 g3^10/(4pi)^8)
b3 = sp.Rational(149753, 6) + 3564 * sp.zeta(3) - (sp.Rational(1078361, 162) + sp.Rational(6508, 27) * sp.zeta(3)) * 6 \
     + (sp.Rational(50065, 162) + sp.Rational(6472, 81) * sp.zeta(3)) * 36 + sp.Rational(1093, 729) * 216
report['g3_4loop'] = dict(own_b3_nf6=float(b3), Buttazzo=float(-butt['g3sq'][4].coeff(g3, 10)))
report['n_monomials_compared'] = nmono
report['n_mismatch'] = nbad
json.dump(report, open(RES, 'w', encoding='utf-8'), indent=1)
print('monomials compared:', nmono, ' mismatches:', nbad)
for c in report['checks'][:60]:
    print(c)
print('g3 4-loop:', report['g3_4loop'])
