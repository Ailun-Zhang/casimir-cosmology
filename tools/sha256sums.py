"""Write or check SHA-256 sums and the file manifest of (a part of) the package.

    python tools/sha256sums.py write [SUBDIR ...] [--out SHA256SUMS.txt]   # default: whole package -> SHA256SUMS.txt
    python tools/sha256sums.py check [SHA256SUMS.txt]
    python tools/sha256sums.py manifest [--out MANIFEST.json]             # path, size and SHA-256 of every file

Paths are written relative to the package root with forward slashes.  Skipped: the run-output tree ``output/``
(except its placeholder ``output/README.md``), caches (``__pycache__``, ``*.pyc``, ``.git``), the third-party build
tree ``third_party/smdr/build/`` (regenerated by ``fetch_and_build.py``), the workflow record ``STATUS.json`` at the
package root, and the two index files themselves (MANIFEST.json is listed in SHA256SUMS.txt).
Run ``manifest`` before ``write`` after any change to the package.
"""
import datetime
import hashlib
import json
import os
import sys

PKG_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {"__pycache__", ".git", ".ipynb_checkpoints"}
SKIP_REL_DIRS = {"output", "third_party/smdr/build"}
KEEP_FILES = {"output/README.md"}
SKIP_REL_FILES = {"STATUS.json", "SHA256SUMS.txt", "MANIFEST.json"}
SKIP_SUFFIX = (".pyc", ".tmp")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def rel(p):
    return os.path.relpath(p, PKG_ROOT).replace(os.sep, "/")


def walk(subdirs):
    for sd in subdirs:
        base = os.path.join(PKG_ROOT, sd)
        if os.path.isfile(base):
            yield base
            continue
        for d, dirs, files in os.walk(base):
            rd = rel(d)
            dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS
                             and (x if rd == "." else rd + "/" + x) not in SKIP_REL_DIRS)
            for fn in sorted(files):
                rf = fn if rd == "." else rd + "/" + fn
                if fn.endswith(SKIP_SUFFIX) or rf in SKIP_REL_FILES:
                    continue
                yield os.path.join(d, fn)
    for k in sorted(KEEP_FILES):
        p = os.path.join(PKG_ROOT, *k.split("/"))
        if (not subdirs or "." in subdirs or k.split("/")[0] in subdirs) and os.path.isfile(p):
            yield p


def write(subdirs, out):
    lines = []
    for p in walk(subdirs or ["."]):
        lines.append("%s  %s" % (sha256(p), rel(p)))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d entries to %s" % (len(lines), rel(out)))


def cff_field(key, default):
    """Top-level scalar of CITATION.cff (the version and repository URL live there; no YAML parser needed)."""
    try:
        with open(os.path.join(PKG_ROOT, "CITATION.cff"), encoding="utf-8") as f:
            for ln in f:
                if ln.startswith(key + ":"):
                    return ln.split(":", 1)[1].strip().strip("\"'") or default
    except OSError:
        pass
    return default


def manifest(out):
    repo = cff_field("repository-code", "").rstrip("/").rsplit("/", 1)[-1]
    name = repo if repo and "XXXX" not in repo else "casimir-cosmology"
    files, tops = [], {}
    for p in walk(["."]):
        r, n = rel(p), os.path.getsize(p)
        files.append({"path": r, "bytes": n, "sha256": sha256(p)})
        t = r.split("/")[0] if "/" in r else "(top level)"
        tops.setdefault(t, {"files": 0, "bytes": 0})
        tops[t]["files"] += 1
        tops[t]["bytes"] += n
    obj = {"name": name, "version": cff_field("version", "1.0"),
           "title": "Code and data for: A Casimir turning point as the beginning of a small flat universe",
           "generated_utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
           "n_files": len(files), "total_bytes": sum(f["bytes"] for f in files),
           "excluded": ["output/ (run outputs; regenerated)", "third_party/smdr/build/ (regenerated)", "__pycache__/, *.pyc",
                        "STATUS.json (workflow record)", "MANIFEST.json and SHA256SUMS.txt themselves"],
           "top_level": tops, "files": files}
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote %s: %d files, %.1f MB" % (rel(out), obj["n_files"], obj["total_bytes"] / 1e6))


def check(path):
    bad = 0
    n = 0
    for ln in open(path, encoding="utf-8"):
        if not ln.strip():
            continue
        h, r = ln.rstrip("\n").split("  ", 1)
        p = os.path.join(PKG_ROOT, r)
        n += 1
        if not os.path.exists(p) or sha256(p) != h:
            bad += 1
            print("MISMATCH", r)
    print("%d files checked, %d mismatches" % (n, bad))
    return bad == 0


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args or args[0] not in ("write", "check", "manifest"):
        print(__doc__)
        sys.exit(2)
    out = None
    if "--out" in args:
        i = args.index("--out")
        out = os.path.abspath(args[i + 1])
        args = args[:i] + args[i + 2:]
    if args[0] == "write":
        write(args[1:], out or os.path.join(PKG_ROOT, "SHA256SUMS.txt"))
    elif args[0] == "manifest":
        manifest(out or os.path.join(PKG_ROOT, "MANIFEST.json"))
    else:
        ok = check(args[1] if len(args) > 1 else os.path.join(PKG_ROOT, "SHA256SUMS.txt"))
        sys.exit(0 if ok else 1)
